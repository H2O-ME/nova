// Generate the token vocabulary table inside `packages/web/ui/DESIGN.md`.
//
// WHY THIS EXISTS
// ---------------
// The design rules used to live in a top-level document that was deleted in the
// 2026-11-20 documentation sweep; the guard script still cites it and the token
// layer keeps growing. Hand-maintaining a 129-row table would drift within a
// week, so the table is DERIVED from `design/tokens/*.css` — the values' only
// home — and a check mode keeps the document honest.
//
// Semantics:
//   --write   regenerate the section between the markers.
//   --check   (default) fail when the committed table no longer matches the
//             token layer. Wired into `pnpm gates`, so a token change without
//             a regenerated table is a red gate, not a stale doc.
//
// The table is deliberately mechanical: name, light/baseline value, dark
// override. "When to use which family" is hand-written prose in DESIGN.md above
// the generated block — token names cannot explain a role, only a value.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(fileURLToPath(import.meta.url), '..', '..');
const tokensDir = join(repoRoot, 'packages', 'web', 'ui', 'src', 'design', 'tokens');
const docPath = join(repoRoot, 'packages', 'web', 'ui', 'DESIGN.md');

const BEGIN = '<!-- tokens:begin (generated by scripts/ui-token-doc.mjs) -->';
const END = '<!-- tokens:end -->';

/** Collapse a declaration value to one readable line. */
const oneLine = (value) => value.replace(/\s+/g, ' ').trim();

/** Escape a value so it cannot break the Markdown table. */
const cell = (value) => oneLine(value).replace(/\|/g, '\\|');

/**
 * Read one token sheet and return the variables it declares.
 * `body[data-nova-dark]` blocks are the dark overrides; everything else is the
 * light/baseline value. First declaration wins, matching CSS cascade order
 * within the file.
 * @param {string} file - sheet file name, for the section heading.
 * @param {string} text - raw sheet text.
 */
function parseSheet(file, text) {
  const stripped = text.replace(/\/\*[\s\S]*?\*\//g, ' ');
  /** @type {Map<string, { light?: string, dark?: string }>} */
  const tokens = new Map();
  for (const block of stripped.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selector = block[1] ?? '';
    const dark = selector.includes('data-nova-dark');
    for (const decl of (block[2] ?? '').matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)) {
      const name = decl[1];
      const value = decl[2];
      if (name === undefined || value === undefined) continue;
      const entry = tokens.get(name) ?? {};
      if (dark) {
        if (entry.dark === undefined) entry.dark = value;
      } else if (entry.light === undefined) {
        entry.light = value;
      }
      tokens.set(name, entry);
    }
  }
  return { file, tokens };
}

const sheets = readdirSync(tokensDir)
  .filter((name) => name.endsWith('.css'))
  .sort()
  .map((name) => parseSheet(name, readFileSync(join(tokensDir, name), 'utf8')));

const total = sheets.reduce((sum, sheet) => sum + sheet.tokens.size, 0);

const lines = [];
lines.push(BEGIN);
lines.push('');
lines.push(
  `token 层共 **${total}** 个变量，分布在 \`src/design/tokens/\` 的 ${sheets.length} 个 sheet。` +
    '本表由 `scripts/ui-token-doc.mjs` 从 token 层生成——**不要手改**，改完 token 跑 `pnpm tokens:doc`。'
);
lines.push('');

for (const sheet of sheets) {
  if (sheet.tokens.size === 0) continue;
  lines.push(`### \`${sheet.file}\``);
  lines.push('');
  lines.push('| 变量 | 亮色 / 基线值 | 暗色覆盖 |');
  lines.push('| --- | --- | --- |');
  for (const [name, entry] of sheet.tokens) {
    const dark = entry.dark === undefined ? '—' : `\`${cell(entry.dark)}\``;
    lines.push(`| \`${name}\` | \`${cell(entry.light ?? entry.dark ?? '')}\` | ${dark} |`);
  }
  lines.push('');
}

lines.push(END);
const generated = lines.join('\n');

const current = (() => {
  try {
    return readFileSync(docPath, 'utf8');
  } catch {
    return undefined;
  }
})();

if (process.argv.includes('--write')) {
  if (current === undefined) {
    console.error(`✗ ${docPath} 不存在：先生成文档骨架（含 markers），再运行 --write。`);
    process.exit(1);
  }
  const begin = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (begin < 0 || end < begin) {
    console.error('✗ DESIGN.md 里找不到 tokens:begin / tokens:end 标记。');
    process.exit(1);
  }
  const next = current.slice(0, begin) + generated + current.slice(end + END.length);
  writeFileSync(docPath, next);
  console.log(`✓ 已生成 token 表：${total} 个变量 / ${sheets.length} 个 sheet。`);
  process.exit(0);
}

if (current === undefined) {
  console.error(`✗ ${docPath} 不存在：运行 pnpm tokens:doc 生成。`);
  process.exit(1);
}
const begin = current.indexOf(BEGIN);
const end = current.indexOf(END);
if (begin < 0 || end < begin) {
  console.error('✗ DESIGN.md 里找不到 tokens:begin / tokens:end 标记。');
  process.exit(1);
}
const committed = current.slice(begin, end + END.length);
if (committed !== generated) {
  console.error('✗ DESIGN.md 的 token 表已过期：token 层变了而文档没跟。');
  console.error('  运行 `pnpm tokens:doc` 重新生成，再提交这一处 diff。');
  process.exit(1);
}
console.log(`✓ DESIGN.md 的 token 表与 token 层一致（${total} 个变量）。`);
